/* ─── Incident card ─────────────────────────────────────────────── */
function IncidentCard({ item, index }: { item: CrimeEvent; index: number }) {
  const [expanded, setExpanded] = useState(false);

  return (
    <div
      className="relative border-b border-slate-100 last:border-0 animate-page-enter"
      style={{ animationDelay: `${Math.min(index * 40, 400)}ms`, animationFillMode: 'both' }}
      data-testid={`timeline-event-${item.id}`}
    >
      {/* Timeline connector */}
      <div className="absolute left-[17px] top-0 bottom-0 w-px bg-slate-100 last:hidden" />

      <div className="relative flex gap-4 py-4 pl-1">
        {/* Dot */}
        <div className={`mt-1 h-4 w-4 shrink-0 rounded-full border-2 ${item.severity?.toLowerCase() === 'high' ? 'border-rose-400 bg-rose-100' : 'border-amber-400 bg-amber-50'}`} />

        <div className="flex-1 min-w-0">
          <div className="flex flex-wrap items-start justify-between gap-2">
            <div>
              <div className="flex flex-wrap items-center gap-2">
                <span className="font-bold text-sm">{item.crimeType}</span>
                {item.severity && (
                  <span className={`rounded-full border px-2 py-0.5 font-mono text-[9px] uppercase font-bold ${severityBadge(item.severity)}`}>
                    {item.severity}
                  </span>
                )}
              </div>
              <div className="mt-1 font-mono text-[10px] text-slate-400">{item.firNumber}</div>
            </div>

            <div className="flex items-center gap-2">
              <span className={`rounded-full border px-2.5 py-1 font-mono text-[9px] uppercase font-bold ${statusBadge(item.status)}`}>
                {item.status}
              </span>
              <button
                onClick={() => exportIncidentReport(item)}
                className="grid h-7 w-7 place-items-center rounded-lg border border-slate-200 bg-white text-slate-400 transition hover:border-[#172735] hover:text-[#172735]"
                title="Export report"
              >
                <Download size={12} />
              </button>
            </div>
          </div>

          <div className="mt-2 flex flex-wrap gap-4 text-xs text-slate-500">
            <span>{item.district} · {item.policeStation}</span>
            <span>{new Date(item.date).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })}</span>
          </div>

          {item.summary && (
            <>
              <button onClick={() => setExpanded((v) => !v)} className="mt-2 text-xs font-bold text-emerald-700 hover:underline">
                {expanded ? 'Hide details' : 'View details'}
              </button>
              {expanded && (
                <p className="mt-2 rounded-lg bg-slate-50 px-3 py-2.5 text-xs leading-6 text-slate-600">
                  {item.summary}
                </p>
              )}
            </>
          )}
        </div>
      </div>
    </div>
  );
}

/* ─── Page ──────────────────────────────────────────────────────── */
export default function Incidents() {
  const q = useGetCrimeTimeline();
  const [search, setSearch] = useState('');
  const [filter, setFilter] = useState('All');
  const [severity, setSeverity] = useState('All');

  const statuses = useMemo(
    () => ['All', ...new Set((q.data ?? []).map((x) => x.status))],
    [q.data]
  );
  const severities = ['All', 'High', 'Medium', 'Low'];

  const filtered = useMemo(
    () =>
      (q.data ?? []).filter((item) => {
        const text = `${item.firNumber} ${item.crimeType} ${item.district} ${item.summary ?? ''}`.toLowerCase();
        const matchSearch = !search || text.includes(search.toLowerCase());
        const matchStatus = filter === 'All' || item.status === filter;
        const matchSev = severity === 'All' || (item.severity ?? '').toLowerCase() === severity.toLowerCase();
        return matchSearch && matchStatus && matchSev;
      }),
    [q.data, search, filter, severity]
  );

  const handleRefresh = () => {
    void q.refetch();
    toast.success('Incident records synced');
  };

  return (
    <>
      <PageHead
        eyebrow="Field records"
        title="Incident timeline"
        detail="A chronological evidence register for current and historical crime events across Karnataka."
        action={
          <button
            onClick={handleRefresh}
            className="inline-flex items-center gap-2 rounded-lg border border-slate-300 bg-white px-4 py-2.5 text-xs font-bold"
            data-testid="button-refresh-incidents"
          >
            <RefreshCw size={14} /> Sync records
          </button>
        }
      />

      <Card>
        {/* Search + filters */}
        <div className="mb-5 flex flex-col gap-3">
          <div className="relative">
            <Search size={16} className="absolute left-3 top-3 text-slate-400" />
            <input
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              placeholder="Search by FIR number, crime type, district or description…"
              className="h-11 w-full rounded-lg border border-slate-300 bg-slate-50 pl-9 pr-10 text-sm outline-none focus:border-emerald-500 focus:bg-white"
              data-testid="input-search-incidents"
            />
            {search && (
              <button onClick={() => setSearch('')} className="absolute right-3 top-3 text-slate-400 hover:text-slate-700">
                <X size={15} />
              </button>
            )}
          </div>

          <div className="flex flex-wrap gap-2">
            {/* Status filters */}
            <div className="flex gap-1.5 overflow-auto">
              {statuses.map((item) => (
                <button
                  key={item}
                  onClick={() => setFilter(item)}
                  className={`whitespace-nowrap rounded-lg border px-3 py-1.5 text-xs font-bold transition ${filter === item ? 'border-[#172735] bg-[#172735] text-white' : 'border-slate-200 bg-white text-slate-500 hover:border-slate-300'}`}
                  data-testid={`button-filter-${item}`}
                >
                  {item}
                </button>
              ))}
            </div>

            <div className="ml-auto flex gap-1.5">
              {severities.map((s) => (
                <button
                  key={s}
                  onClick={() => setSeverity(s)}
                  className={`rounded-lg border px-3 py-1.5 text-xs font-bold transition ${severity === s
                    ? s === 'High' ? 'border-rose-600 bg-rose-600 text-white'
                      : s === 'Medium' ? 'border-amber-500 bg-amber-500 text-white'
                        : 'border-[#172735] bg-[#172735] text-white'
                    : 'border-slate-200 bg-white text-slate-500 hover:border-slate-300'}`}
                >
                  {s}
                </button>
              ))}
            </div>
          </div>

          {(search || filter !== 'All' || severity !== 'All') && (
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <span>{filtered.length} of {q.data?.length ?? 0} records</span>
              <button onClick={() => { setSearch(''); setFilter('All'); setSeverity('All'); }} className="font-bold text-emerald-700 hover:underline">
                Clear filters
              </button>
            </div>
          )}
        </div>

        {/* Timeline */}
        <QueryState
          loading={q.isLoading}
          error={q.error}
          empty={!filtered.length}
          onRetry={() => q.refetch()}
          emptyMessage="No incidents match the current filters."
        >
          <div className="pl-4">
            {filtered.map((item, i) => <IncidentCard item={item} index={i} key={item.id} />)}
          </div>
        </QueryState>
      </Card>
    </>
  );
}
