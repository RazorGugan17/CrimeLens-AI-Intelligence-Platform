import { useMemo, useState } from 'react';
import { Download, RefreshCw, Search, X } from 'lucide-react';
import { useGetCrimeTimeline } from '@workspace/api-client-react';
import type { CrimeEvent } from '@workspace/api-client-react';
import { toast } from 'sonner';
import { Card, PageHead, QueryState } from '@/components/shared';

/* ─── Severity + status styling ─────────────────────────────────── */
function severityBadge(s?: string) {
  if (!s) return 'bg-slate-50 text-slate-500 border-slate-200';
  switch (s.toLowerCase()) {
    case 'high': return 'bg-rose-50 text-rose-700 border-rose-200';
    case 'medium': return 'bg-amber-50 text-amber-700 border-amber-200';
    default: return 'bg-slate-50 text-slate-600 border-slate-200';
  }
}

function statusBadge(s: string) {
  const l = s.toLowerCase();
  if (l.includes('open')) return 'bg-amber-50 text-amber-700 border-amber-200';
  if (l.includes('closed') || l.includes('resolved')) return 'bg-emerald-50 text-emerald-700 border-emerald-200';
  return 'bg-sky-50 text-sky-700 border-sky-200';
}

